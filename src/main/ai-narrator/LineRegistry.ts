export function pickLine(eventType: string): { text: string; preset: VoicePreset; prefix: string } | null {
    const line = LINE_REGISTRY[eventType];
    if (!line) return null;
    const text = line.variants[Math.floor(Math.random() * line.variants.length)];
    return {
        text,
        preset: line.preset,
        prefix: line.filePrefix ?? eventType
    };
}

/** Все поддерживаемые события нарратора */
export function getNarratorEvents(): string[] {
    return Object.keys(LINE_REGISTRY);
}